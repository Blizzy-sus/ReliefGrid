/**
 * Runs the allocation scenarios used in the documentation and writes docs/RESULTS.md.
 *   npm run scenarios
 * Everything is deterministic: fixed clock, fixed random seeds.
 */
import fs from 'node:fs';
import path from 'node:path';
import { performance } from 'node:perf_hooks';
import { fileURLToPath } from 'node:url';
import { allocate, fairShare, priorityScore } from '../server/allocation/engine.js';
import { approvedQuantity } from '../server/services/requests.js';
import { openDb, migrate } from '../server/db.js';
import { seedDatabase } from '../server/seed.js';
import { previewAllocation, commitAllocation } from '../server/services/allocation.js';
import { checkIntegrity } from '../server/services/reports.js';
import { fifo, proportionalToNeed, strictPriority, priorityOfRemaining, jain } from './baselines.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const NOW = new Date('2026-07-15T12:00:00Z');
const hoursAgo = (h) => new Date(NOW.getTime() - h * 3_600_000).toISOString();
const WEIGHT = { Critical: 6, High: 3.5, Moderate: 2, Low: 1 };
const fmt = (n) => Number(n).toLocaleString('en-US');
const pct = (x) => `${Math.round(x * 100)}%`;
const out = [];
const w = (s = '') => out.push(s);
const table = (head, rows) => { w(`| ${head.join(' | ')} |`); w(`|${head.map((_, i) => (i === 0 ? ' :-- ' : ' --: ')).join('|')}|`); rows.forEach((r) => w(`| ${r.join(' | ')} |`)); w(); };

// -------------------------------------------------------------------- helpers
function entriesFor(camps) {
  return camps.map((c, i) => {
    const p = priorityScore({ urgencyWeight: WEIGHT[c.urgency], population: c.pop, vulnerableCount: Math.round(c.pop * c.vul), createdAt: hoursAgo(c.wait), now: NOW });
    return { id: i, name: c.name, urgency: c.urgency, pop: c.pop, vul: c.vul, wait: c.wait, approved: c.need, prior: c.prior || 0, need: c.need - (c.prior || 0), score: p.score, createdAt: hoursAgo(c.wait), parts: p };
  });
}

function compare(entries, supply, title) {
  const methods = [
    ['**ReliefGrid**', fairShare(entries, supply).shares],
    ['First come, first served', fifo(entries, supply)],
    ['Equal share of need (ignores urgency)', proportionalToNeed(entries, supply)],
    ['Strict priority (winner takes all)', strictPriority(entries, supply)],
  ];
  const cov = (m) => entries.map((e) => (e.prior + (m.get(e.id) || 0)) / e.approved);
  w(`#### ${title}`);
  w();
  table(['Camp', 'Urgency', 'People', 'At-risk', 'Waiting', 'Needs', 'Priority score', ...methods.map(([n]) => `${n} (units / coverage)`)],
    entries.map((e) => [e.name, e.urgency, fmt(e.pop), pct(e.vul), `${e.wait}h`, fmt(e.need), e.score.toFixed(2),
      ...methods.map(([, m]) => `${fmt(m.get(e.id))} / ${pct((e.prior + m.get(e.id)) / e.approved)}`)]));
  const mean = (xs) => xs.reduce((a, b) => a + b, 0) / (xs.length || 1);
  const rows = methods.map(([name, m]) => {
    const c = cov(m);
    const by = (u) => mean(entries.filter((e) => e.urgency === u).map((e) => c[e.id]));
    const crit = entries.some((e) => e.urgency === 'Critical') ? pct(by('Critical')) : '–';
    const low = entries.some((e) => e.urgency === 'Low') ? pct(by('Low')) : '–';
    return [name, crit, low, pct(Math.min(...c)), String(c.filter((x) => x === 0).length), jain(c).toFixed(2), fmt([...m.values()].reduce((a, b) => a + b, 0))];
  });
  table(['Method', 'Critical coverage', 'Low coverage', 'Worst-off camp', 'Camps left with nothing', 'Jain index*', 'Units used'], rows);
}

// -------------------------------------------------------------------- scenario 1
w('# ReliefGrid: scenario results');
w();
w('Generated by `npm run scenarios` (fixed clock and seeds, so results are reproducible). **Coverage** = (units already allocated + units allocated now) ÷ approved units. ');
w('*Jain index is a standard fairness score for coverage ratios: 1.00 = everyone has the same coverage. ReliefGrid deliberately trades some of it for priority, so read it together with the Critical and worst-off columns.');
w();
w('## 1. Abundant stock');
w();
{
  const e = entriesFor([
    { name: 'Riverside School', pop: 800, vul: 0.28, urgency: 'Critical', wait: 5, need: 6000 },
    { name: 'Temple Hall', pop: 300, vul: 0.3, urgency: 'High', wait: 20, need: 2500 },
    { name: 'Stadium', pop: 950, vul: 0.27, urgency: 'Low', wait: 12, need: 7000 }]);
  const r = fairShare(e, 20000);
  w(`Stock 20,000 L, demand ${fmt(e.reduce((s, x) => s + x.need, 0))} L. Scarce: **${r.scarce}**. Allocations: ${e.map((x) => `${x.name} ${fmt(r.shares.get(x.id))}/${fmt(x.need)}`).join(', ')}.`);
  w();
  w('When nothing is short, priority is irrelevant and everyone is served in full.');
  w();
}

// -------------------------------------------------------------------- scenario 2
w('## 2. Moderate scarcity: one water convoy for six camps');
w();
w('Water is available for 39% of open demand. Camps differ in size, vulnerability, urgency and how long they have waited.');
w();
{
  const camps = [
    { name: 'Riverside School', pop: 800, vul: 0.28, urgency: 'Critical', wait: 5, need: 12000 },
    { name: 'Temple Hall', pop: 300, vul: 0.32, urgency: 'High', wait: 20, need: 4500 },
    { name: 'Stadium', pop: 950, vul: 0.27, urgency: 'High', wait: 12, need: 14000 },
    { name: 'Town Hall', pop: 270, vul: 0.22, urgency: 'Moderate', wait: 30, need: 4000 },
    { name: 'Polytechnic', pop: 700, vul: 0.21, urgency: 'Moderate', wait: 8, need: 10500 },
    { name: 'Youth Hostel', pop: 230, vul: 0.2, urgency: 'Low', wait: 44, need: 3400 },
  ];
  compare(entriesFor(camps), 19000, 'Water, 19,000 L for 48,400 L of demand');
  w('First-come-first-served gives the long-waiting low-urgency hostel everything it asked for while the **Critical** camp, which asked last, gets nothing. Equal sharing ignores the emergency entirely. Strict priority serves the critical camp fully but leaves the three lowest-priority camps with nothing. ReliefGrid gives the critical camp the largest share of what it needs, gives every camp something, and rewards camps that have waited long.');
  w();
}

