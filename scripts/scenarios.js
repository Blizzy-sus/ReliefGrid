// -------------------------------------------------------------------- scenario 4
w('## 4. Over-claiming is capped by a planning standard');
w();
{
  const rows = [[1000, 5, 3, 40000], [1000, 5, 3, 15000], [200, 0.5, 3, 900], [300, null, 3, 500]].map(([pop, std, days, req]) => {
    const a = approvedQuantity({ requested: req, standard: std, population: pop, horizonDays: days });
    return [fmt(pop), std ?? 'none', fmt(req), fmt(a.approved), a.note ? 'trimmed' : 'as requested'];
  });
  table(['Camp population', 'Standard (per person/day)', 'Requested', 'Approved', 'Outcome'], rows);
  w('A camp cannot inflate its share by asking for more than the standard allows. Items with no standard (tarpaulins, insulin) are approved as requested.');
  w();
}

// -------------------------------------------------------------------- scenario 5
w('## 5. Fairness across successive rounds (deficit awareness)');
w();
w('Two camps with identical priority each request 1,000 units. Round 1: 400 units arrive but only camp A has a request open, so A receives all 400. Round 2: camp B has now asked too and 600 more units arrive.');
w();
{
  const A = { name: 'A (served in round 1)', pop: 500, vul: 0.2, urgency: 'High', wait: 10, need: 1000, prior: 400 };
  const B = { name: 'B (asks in round 2)', pop: 500, vul: 0.2, urgency: 'High', wait: 10, need: 1000, prior: 0 };
  const e = entriesFor([A, B]);
  const smart = fairShare(e, 600).shares;
  const naive = priorityOfRemaining(e.map((x) => ({ ...x, need: x.approved - x.prior })), 600, fairShare);
  table(['Camp', 'Already holds', 'Naive: share of remaining need', 'Cumulative coverage (naive)', 'ReliefGrid (deficit-aware)', 'Cumulative coverage (ReliefGrid)'],
    e.map((x) => [x.name, fmt(x.prior), fmt(naive.get(x.id)), pct((x.prior + naive.get(x.id)) / x.approved), fmt(smart.get(x.id)), pct((x.prior + smart.get(x.id)) / x.approved)]));
  const [a, b] = e;
  w(`A method that only looks at remaining need gives camp A another ${fmt(naive.get(a.id))} units although it already holds ${pct(a.prior / a.approved)}, ending at ${pct((a.prior + naive.get(a.id)) / a.approved)} for A against ${pct(naive.get(b.id) / b.approved)} for B. ReliefGrid brings both camps to the same cumulative coverage (${pct((a.prior + smart.get(a.id)) / a.approved)}): A +${fmt(smart.get(a.id))}, B +${fmt(smart.get(b.id))}.`);
  w();
}

// -------------------------------------------------------------------- scenario 6
w('## 6. Waiting is rewarded, so low urgency is not starved forever');
w();
{
  const camps = [
    { name: 'Low urgency, waited 72h', pop: 400, vul: 0.2, urgency: 'Low', wait: 72, need: 1000 },
    { name: 'Low urgency, just asked', pop: 400, vul: 0.2, urgency: 'Low', wait: 0, need: 1000 },
    { name: 'Moderate, just asked', pop: 400, vul: 0.2, urgency: 'Moderate', wait: 0, need: 1000 },
  ];
  const e = entriesFor(camps);
  const r = fairShare(e, 900).shares;
  table(['Request', 'Urgency weight', 'Vulnerability', 'Aging', 'Priority', 'Allocated of 1,000', 'Coverage'],
    e.map((x) => [x.name, WEIGHT[x.urgency], x.parts.vulnerabilityFactor.toFixed(2), x.parts.agingFactor.toFixed(2), x.score.toFixed(2), fmt(r.get(x.id)), pct(r.get(x.id) / x.approved)]));
  w('Aging (up to +50% after 48 h) lets a request that has waited three days overtake an identical fresh one, but it does not overturn a genuine difference in urgency.');
  w();
}

// -------------------------------------------------------------------- scenario 7: the demo database
w('## 7. The seeded demo incident, end to end');
w();
{
  const db = openDb(':memory:');
  migrate(db);
  seedDatabase(db, { now: NOW });
  const plan = previewAllocation(db, {}, NOW);
  w(`Seed: 12 camps, 4 warehouses, 18 items, two committed historical runs. Current open demand: **${plan.totals.requestLines} request lines**; **${plan.totals.scarceItems} items are scarce**.`);
  w();
  table(['Item', 'In stock', 'Open demand', 'Coverable', 'Status'],
    plan.items.map((i) => [i.itemName, `${fmt(i.supply)} ${i.unit}`, `${fmt(i.demand)} ${i.unit}`, pct(Math.min(1, i.supply / i.demand)), i.scarce ? 'scarce, rationed' : 'sufficient']));
  w('Packaged drinking water, request lines starting from zero (sorted by priority):');
  w();
  const water = plan.decisions.filter((d) => d.itemName === 'Packaged drinking water' && d.prior === 0).sort((a, b) => b.score - a.score);
  table(['Camp', 'Urgency', 'Priority', 'Approved (L)', 'Allocated (L)', 'Coverage'],
    water.map((d) => [d.campName, d.urgencyLabel, d.score.toFixed(2), fmt(d.approved), fmt(d.allocated), pct(d.cumulativeCoverage)]));
  const sample = plan.decisions.find((d) => d.itemName === 'Packaged drinking water' && d.prior === 0 && d.urgencyLabel === 'Critical');
  w('Plain-language explanation shown to the camp:');
  w();
  w(`> ${sample.explanation}`);
  w();
  // commit and verify invariants
  const admin = { id: 1, role: 'admin' };
  const t0 = performance.now();
  const run = commitAllocation(db, admin, { note: 'scenario run' }, NOW);
  const ms = performance.now() - t0;
  const check = checkIntegrity(db);
  const reserved = db.prepare('SELECT SUM(quantity_reserved) AS r, SUM(quantity_on_hand) AS oh FROM inventory').get();
  w(`Committing the run took **${ms.toFixed(0)} ms** (one transaction): ${run.shipmentIds.length} shipments planned, ${fmt(run.totals.unitsAllocated)} units reserved. Reserved stock (${fmt(reserved.r)}) never exceeds stock on hand (${fmt(reserved.oh)}); integrity checks: **${check.ok ? 'all passed' : 'FAILED'}**.`);
  w();
  db.close();
}

// -------------------------------------------------------------------- scenario 8: scale
w('## 8. Performance');
w();
{
  let seed = 12345;
  const rand = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; };
  const items = new Map(Array.from({ length: 18 }, (_, i) => [i + 1, { name: `Item ${i + 1}`, unit: 'u' }]));
  const warehouses = new Map(Array.from({ length: 12 }, (_, i) => [i + 1, { name: `W${i + 1}`, latitude: 10 + rand() * 1.5, longitude: 79 + rand() * 1 }]));
  const timeRun = (lines) => {
    const camps = new Map(Array.from({ length: Math.ceil(lines / 8) }, (_, i) => [i + 1, { name: `C${i + 1}`, latitude: 10 + rand() * 1.5, longitude: 79 + rand() * 1 }]));
    const requests = Array.from({ length: lines }, (_, i) => ({
      requestItemId: i + 1, requestId: i + 1, campId: (i % camps.size) + 1, itemId: (i % 18) + 1, approved: 100 + Math.floor(rand() * 900), prior: 0,
      urgencyLabel: 'High', urgencyWeight: [1, 2, 3.5, 6][Math.floor(rand() * 4)], population: 500, vulnerableCount: 100, createdAt: hoursAgo(rand() * 48),
    }));
    const demand = new Map();
    for (const r of requests) demand.set(r.itemId, (demand.get(r.itemId) || 0) + r.approved);
    const stock = [];
    for (const [itemId, d] of demand) for (const wid of warehouses.keys()) stock.push({ warehouseId: wid, itemId, available: Math.floor((d * 0.4) / warehouses.size) });
    const t0 = performance.now();
    const res = allocate({ requests, stock, camps, warehouses, items, now: NOW });
    const ms = performance.now() - t0;
    const allocated = res.decisions.reduce((s, d) => s + d.allocated, 0);
    const supply = stock.reduce((s, x) => s + x.available, 0);
    return [fmt(lines), '12', ms.toFixed(0) + ' ms', allocated <= supply ? 'yes' : 'NO'];
  };
  table(['Request lines', 'Warehouses', 'Allocation time (pure engine)', 'Never exceeds stock'], [timeRun(100), timeRun(500), timeRun(2000), timeRun(5000)]);
  w('Each item is solved independently in O(n²) worst case over its own request lines (n is lines per item), so even thousands of open lines allocate in well under a second.');
  w();
}

